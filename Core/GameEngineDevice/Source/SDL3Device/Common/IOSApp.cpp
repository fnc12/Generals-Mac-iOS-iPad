bool isShippedAssetName(const std::string &name, const IOSApp::Game &game)
{
	if (name.size() > 4 && name.compare(name.size() - 4, 4, ".big") == 0) {
		return true;
	}
	static const char *const common[] = { "Data", "Window", "fonts", "_CommonRedist", "dxvk.conf" };
	for (const char *asset : common) {
		if (name == asset) {
			return true;
		}
	}
	const std::string exe = game.executableName;
	if (name == exe + ".dxvk-cache" || name == exe + "_d3d9.log") {
		return true;
	}
	for (const char *const *asset = game.extraShippedAssets; asset != nullptr && *asset != nullptr; ++asset) {
		if (name == *asset) {
			return true;
		}
	}
	return false;
}

