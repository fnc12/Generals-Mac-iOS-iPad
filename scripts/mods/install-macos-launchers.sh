#!/usr/bin/env bash
# Install the two game apps plus one launcher per mod into ~/GeneralsX/Apps.
#
#   ./scripts/mods/install-macos-launchers.sh
#
# Inputs (already built):
#   GeneralsX-macos-arm64.zip     base game   (bundle-macos-generals.sh)
#   GeneralsXZH-macos-arm64.zip   Zero Hour   (bundle-macos-zh.sh)
#   build/mods/<Name>-generals.big, build/mods/<Name>-zh.big   (make_big.py)
#
# Result in ~/GeneralsX/Apps:
#   GeneralsX.app                 base game, no mod
#   GeneralsXZH.app               Zero Hour, no mod
#   GeneralsX + <Name>.app        base game with -mod ~/GeneralsX/Mods/<Name>-generals.big
#   GeneralsXZH + <Name>.app      Zero Hour with -mod ~/GeneralsX/Mods/<Name>-zh.big
#
# A mod launcher is a tiny app that starts the real app with -mod; the
# original .big archives are never touched. Delete a launcher (or the .big in
# ~/GeneralsX/Mods) to remove the mod.
#
# Game data is not copied. Expected locations (same as the app defaults):
#   ~/GeneralsX/GeneralsZH            Zero Hour data
#   ~/GeneralsX/Generals              base game data
#
# Big mods (Rise of the Reds, ShockWave, ...): set ZH_SOURCE to the original
# Zero Hour folder (Steam / EA layout, with ZH_Generals/ inside) and put each
# unpacked mod into ~/GeneralsX/ModFiles/<Mod>. Then also:
#   ~/GeneralsX/Games/ZH              clean Zero Hour (symlinks, no ZH_Generals/;
#                                     ~/GeneralsX/GeneralsZH should point here)
#   ~/GeneralsX/Games/ZH-<Mod>        Zero Hour + mod (symlinks, make_mod_game_dir.py)
#   GeneralsXZH + <Mod>.app           runs Zero Hour from Games/ZH-<Mod> with its
#                                     own settings/saves in ~/GeneralsX/Profiles/<Mod>
#                                     (HOME is redirected; the engine keeps user data
#                                     under $HOME/Library/Application Support)
#
#   ZH_SOURCE=~/GeneralsX/steam/"Command & Conquer Generals - Zero Hour" \
#       ./scripts/mods/install-macos-launchers.sh
set -euo pipefail

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
APPS_DIR="${HOME}/GeneralsX/Apps"
MODS_DIR="${HOME}/GeneralsX/Mods"

mkdir -p "${APPS_DIR}" "${MODS_DIR}"

for zip in GeneralsX-macos-arm64.zip GeneralsXZH-macos-arm64.zip; do
    if [[ ! -f "${PROJECT_ROOT}/${zip}" ]]; then
        echo "ERROR: ${zip} not found in ${PROJECT_ROOT}; run the bundle script first." >&2
        exit 1
    fi
    tmp="$(mktemp -d)"
    unzip -q "${PROJECT_ROOT}/${zip}" -d "${tmp}"
    app="$(find "${tmp}" -maxdepth 1 -name '*.app' | head -1)"
    rm -rf "${APPS_DIR}/$(basename "${app}")"
    mv "${app}" "${APPS_DIR}/"
    rm -rf "${tmp}"
    echo "  + ${APPS_DIR}/$(basename "${app}")"
done

# make_launcher <target app> <name> <launch body lines...>
make_launcher() {
    local target_app="$1" name="$2"
    shift 2
    local bundle="${APPS_DIR}/${name}.app"
    rm -rf "${bundle}"
    mkdir -p "${bundle}/Contents/MacOS"
    cat > "${bundle}/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleExecutable</key><string>launch</string>
    <key>CFBundleIdentifier</key><string>local.generalsx.modlauncher.$(echo "${name}" | tr -cd 'A-Za-z0-9')</string>
    <key>CFBundleName</key><string>${name}</string>
    <key>CFBundlePackageType</key><string>APPL</string>
</dict>
</plist>
EOF
    cat > "${bundle}/Contents/MacOS/launch" <<EOF
#!/bin/bash
# ${name}: generated by install-macos-launchers.sh
$(printf '%s\n' "$@")
EOF
    chmod +x "${bundle}/Contents/MacOS/launch"
    echo "  + ${bundle}"
}

shopt -s nullglob
for big in "${PROJECT_ROOT}"/build/mods/*-generals.big "${PROJECT_ROOT}"/build/mods/*-zh.big; do
    cp "${big}" "${MODS_DIR}/"
    file="$(basename "${big}" .big)"
    mod="${file%-*}"
    case "${file}" in
        *-generals) target=GeneralsX.app; name="GeneralsX + ${mod}" ;;
        *-zh)       target=GeneralsXZH.app; name="GeneralsXZH + ${mod}" ;;
        *) continue ;;
    esac
    make_launcher "${target}" "${name}" \
        "exec \"${APPS_DIR}/${target}/Contents/MacOS/run.sh\" -mod \"${MODS_DIR}/${file}.big\" \"\$@\""
done

if [[ -n "${ZH_SOURCE:-}" ]]; then
    GAMES_DIR="${HOME}/GeneralsX/Games"
    MAKE_DIR="${PROJECT_ROOT}/scripts/mods/make_mod_game_dir.py"
    empty="$(mktemp -d)"
    python3 "${MAKE_DIR}" --exclude ZH_Generals "${ZH_SOURCE}" "${empty}" "${GAMES_DIR}/ZH"
    rmdir "${empty}"
    for mod_dir in "${HOME}"/GeneralsX/ModFiles/*/; do
        mod="$(basename "${mod_dir}")"
        python3 "${MAKE_DIR}" --exclude ZH_Generals "${ZH_SOURCE}" "${mod_dir}" "${GAMES_DIR}/ZH-${mod}"
        make_launcher GeneralsXZH.app "GeneralsXZH + ${mod}" \
            "export CNC_GENERALS_ZH_PATH=\"${GAMES_DIR}/ZH-${mod}\"" \
            "export CNC_GENERALS_PATH=\"\${CNC_GENERALS_PATH:-${HOME}/GeneralsX/Generals}\"" \
            "export HOME=\"${HOME}/GeneralsX/Profiles/${mod}\"" \
            "mkdir -p \"\$HOME\"" \
            "exec \"${APPS_DIR}/GeneralsXZH.app/Contents/MacOS/run.sh\" \"\$@\""
    done
fi

echo "Done. Launch from Finder (${APPS_DIR}) or e.g.:"
echo "  open \"${APPS_DIR}/GeneralsXZH + HelloMod.app\""
