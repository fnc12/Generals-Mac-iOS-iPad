# Install the Windows x64 builds plus one launcher per game / mod into one folder.
#
#   powershell -ExecutionPolicy Bypass -File install-windows-launchers.ps1 `
#       -ZHBundle <dir with GeneralsXZH.exe> -GeneralsBundle <dir with GeneralsX.exe>
#
# Result in $Root (default D:\GeneralsX, must be on the same drive as the game
# for hard links):
#   Apps\GeneralsXZH\, Apps\GeneralsX\     the two builds (copied)
#   Games\ZH\                              clean Zero Hour: links to the Steam
#                                          folder without ZH_Generals\ (see
#                                          make_mod_game_dir.py)
#   Games\ZH-<Mod>\                        Zero Hour + a big mod (links)
#   Mods\<Name>-zh.big, <Name>-generals.big  one-file mods used with -mod
#   ModFiles\<Mod>\                        unpacked big mods (input, not touched)
#   "Generals.bat", "Zero Hour.bat",
#   "Generals + <Name>.bat", "Zero Hour + <Name>.bat"   launchers
#
# Nothing in the Steam folders is changed. Delete a launcher (and its Games\
# folder) to remove a mod.
param(
    [Parameter(Mandatory = $true)][string]$ZHBundle,
    [Parameter(Mandatory = $true)][string]$GeneralsBundle,
    [string]$Root = 'D:\GeneralsX',
    [string]$SteamCommon = 'D:\Program Files (x86)\Steam\steamapps\common',
    [string]$Python = 'python'
)
$ErrorActionPreference = 'Stop'
$zhData = Join-Path $SteamCommon 'Command & Conquer Generals - Zero Hour'
$genData = Join-Path $SteamCommon 'Command and Conquer Generals'
$makeDir = Join-Path $PSScriptRoot 'make_mod_game_dir.py'
foreach ($p in @($ZHBundle, $GeneralsBundle, $zhData, $genData, $makeDir)) {
    if (-not (Test-Path -LiteralPath $p)) { throw "not found: $p" }
}
foreach ($d in 'Apps', 'Games', 'Mods', 'ModFiles') { New-Item -ItemType Directory -Force (Join-Path $Root $d) | Out-Null }

# 1. The two builds.
foreach ($pair in @(@($ZHBundle, 'GeneralsXZH'), @($GeneralsBundle, 'GeneralsX'))) {
    $dst = Join-Path $Root "Apps\$($pair[1])"
    if (Test-Path $dst) { Remove-Item $dst -Recurse -Force }
    Copy-Item -LiteralPath $pair[0] -Destination $dst -Recurse
    Write-Host "  + $dst"
}

function New-GameDir([string]$modFiles, [string]$out) {
    & $Python $makeDir --exclude ZH_Generals $zhData $modFiles $out
    if ($LASTEXITCODE -ne 0) { throw "make_mod_game_dir.py failed for $out" }
}

function New-Launcher([string]$name, [string]$exe, [string]$dataDir, [string]$extraArgs) {
    # $dataDir is the game folder the exe runs from: Games\ZH[-Mod] for Zero Hour,
    # the Steam Generals folder for the base game.
    $bat = Join-Path $Root "$name.bat"
    $zhPath = if ($exe -like '*GeneralsXZH.exe') { $dataDir } else { Join-Path $Root 'Games\ZH' }
    @(
        '@echo off'
        "rem $name - generated by install-windows-launchers.ps1"
        "set `"CNC_GENERALS_PATH=$genData`""
        "set `"CNC_GENERALS_ZH_PATH=$zhPath`""
        "cd /d `"$dataDir`""
        "start `"`" `"$exe`" $extraArgs %*"
    ) | Set-Content -LiteralPath $bat -Encoding OEM
    Write-Host "  + $bat"
}

$zhExe = Join-Path $Root 'Apps\GeneralsXZH\GeneralsXZH.exe'
$genExe = Join-Path $Root 'Apps\GeneralsX\GeneralsX.exe'

# 2. Clean games.
$empty = Join-Path $Root 'ModFiles\_none'
New-Item -ItemType Directory -Force $empty | Out-Null
New-GameDir $empty (Join-Path $Root 'Games\ZH')
New-Launcher 'Zero Hour' $zhExe (Join-Path $Root 'Games\ZH') ''
New-Launcher 'Generals' $genExe $genData ''

# 3. One-file mods (-mod).
foreach ($big in Get-ChildItem (Join-Path $Root 'Mods') -Filter *.big -ErrorAction SilentlyContinue) {
    $stem = $big.BaseName
    if ($stem -like '*-zh') {
        New-Launcher "Zero Hour + $($stem -replace '-zh$','')" $zhExe (Join-Path $Root 'Games\ZH') "-mod `"$($big.FullName)`""
    } elseif ($stem -like '*-generals') {
        New-Launcher "Generals + $($stem -replace '-generals$','')" $genExe $genData "-mod `"$($big.FullName)`""
    }
}

# 4. Big Zero Hour mods: every folder in ModFiles\ (except _none) gets its own game folder.
foreach ($mod in Get-ChildItem (Join-Path $Root 'ModFiles') -Directory | Where-Object { $_.Name -ne '_none' }) {
    $out = Join-Path $Root "Games\ZH-$($mod.Name)"
    New-GameDir $mod.FullName $out
    New-Launcher "Zero Hour + $($mod.Name)" $zhExe $out ''
}
Write-Host "Done. Launchers are in $Root"
